"""Regenerate EVALUATION_REPORT.md by actually running the pipeline.

Every number in the report comes from this script. Nothing is typed by hand,
so the report can always be reproduced with:

    python scripts/run_evaluation.py
"""

import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.evaluator import evaluate, format_report          # noqa: E402
from src.redactor import redact_document                   # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def load_annotations(path: Path):
    """Read a ground-truth file, which may be a bare list or a scoped object."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, list):
        return [(d["text"], d["type"]) for d in data], None
    entities = [(d["text"], d["type"]) for d in data["entities"]]
    return entities, data.get("scope")


def run(doc_path: Path, gt_path: Path, label: str, write_docx: bool):
    out_path = ROOT / "output" / f"{doc_path.stem} - REDACTED.docx"
    result = redact_document(str(doc_path), str(out_path) if write_docx else None)

    gt, scope = load_annotations(gt_path)

    predicted = [(e.text, e.type) for e in result.entities]
    if scope:
        # Restrict predictions to the annotated region, otherwise correct
        # detections elsewhere in the document would be counted as false
        # positives against an annotation set that never covered them.
        lo, hi = scope["unit_start"], scope["unit_end"]
        predicted = [
            (e.text, e.type) for e in result.entities if lo <= e.unit <= hi
        ]

    report = evaluate(predicted, gt, corpus=label)
    return result, report, scope


def main() -> None:
    corpora = [
        ("Synthetic fixture", "input/synthetic_sample.docx",
         "data/ground_truth_synthetic.json"),
        ("Red Herring Prospectus (real)", "input/Red Herring Prospectus.docx",
         "data/ground_truth_prospectus.json"),
    ]

    sections = [
        "# PII Redaction - Evaluation Report",
        "",
        f"Generated by `scripts/run_evaluation.py` on {date.today().isoformat()}. "
        "Every number below is produced by running the pipeline; none are estimated.",
        "",
        "**Accuracy** here means `TP / (TP + FP + FN)` at entity level. Token-level "
        "accuracy is deliberately not reported: in a document that is >99% non-PII "
        "text, predicting nothing at all would score ~99%, which is meaningless.",
        "",
    ]

    for label, doc_rel, gt_rel in corpora:
        doc_path, gt_path = ROOT / doc_rel, ROOT / gt_rel
        if not doc_path.exists():
            sections += [f"## {label}", "", f"_Skipped: `{doc_rel}` not present._", ""]
            continue

        print(f"Running {label} ...")
        result, report, scope = run(doc_path, gt_path, label, write_docx=True)

        sections += [
            f"## {label}",
            "",
            f"- Paragraphs / table cells scanned: **{result.text_units}**",
            f"- PII occurrences replaced: **{result.total_entities}**",
            f"- Unique entities mapped: **{len(result.replacement_map)}**",
            f"- Images found / neutralised: **{result.images_found} / "
            f"{result.images_blanked}**",
        ]
        if scope:
            sections.append(
                f"- Evaluation scope: text units **{scope['unit_start']}-"
                f"{scope['unit_end']}** (exhaustively annotated)"
            )
        sections += ["", format_report(report), ""]

        if report.false_positives:
            sections += ["**False positives**", ""]
            sections += [f"- `{t}` ({ty})" for t, ty in report.false_positives[:30]]
            sections.append("")
        if report.false_negatives:
            sections += ["**False negatives**", ""]
            sections += [f"- `{t}` ({ty})" for t, ty in report.false_negatives[:30]]
            sections.append("")

    out = ROOT / "EVALUATION_REPORT.md"
    out.write_text("\n".join(sections), encoding="utf-8")
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
